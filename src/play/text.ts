/** 效果或系统文字：优先中文系统提示，其次卡片自己的英文说明。 */
export function describe(data: EngineData, desc: bigint | number): string {
  const d = BigInt(desc);
  if (d > 0n && d < 10000n && SYSTEM_ZH[Number(d)]) return SYSTEM_ZH[Number(d)];
  return data.describe(d).replace(/%ls/g, "").trim();
}

export const POSITION_LABEL: Record<number, string> = { 1: "表侧攻击", 2: "里侧攻击", 4: "表侧守备", 8: "里侧守备" };

export function placeLabel(location: number, sequence: number): string {
  if (location === 4) return sequence >= 5 ? `额外怪兽区（${sequence === 5 ? "左" : "右"}）` : `怪兽区 ${sequence + 1}`;
  if (sequence === 5) return "场地区";
  if (sequence >= 6) return `灵摆区（${sequence === 6 ? "左" : "右"}）`;
  return `魔陷区 ${sequence + 1}`;
}

